/**
 * Utilidades para BPMN 2.0:
 * - Limpieza de XML generado por IA (eliminación de markdown fences, BOM, espacios).
 * - Generador automático de Diagram Interchange (BPMNDiagram/BPMNPlane) cuando el XML carece de coordenadas visuales.
 * - Plantillas listas para procesos AS-IS y TO-BE.
 * - Prompt optimizado para Gemini / Claude / ChatGPT.
 */

export interface SanitizeResult {
  xml: string;
  autoGeneratedDiagram: boolean;
  warnings?: string[];
}

/**
 * Limpia el texto de entrada:
 * - Quita bloques de markdown ```xml o ```bpmn
 * - Quita BOM (\uFEFF)
 * - Si falta <bpmndi:BPMNDiagram>, autogenera la distribución visual para bpmn-js
 */
export function sanitizeAndPrepareBpmn(rawText: string): SanitizeResult {
  let cleaned = (rawText || "").trim();

  // Quitar BOM si existe
  if (cleaned.charCodeAt(0) === 0xfeff) {
    cleaned = cleaned.slice(1).trim();
  }

  // Quitar bloques markdown: ```xml ... ``` o ```bpmn ... ``` o ``` ... ```
  const codeBlockMatch = cleaned.match(/^```(?:xml|bpmn)?\s*([\s\S]*?)```$/i);
  if (codeBlockMatch) {
    cleaned = codeBlockMatch[1].trim();
  } else {
    // Si contiene ``` en alguna parte, extraer el primer bloque xml/bpmn
    const innerBlock = cleaned.match(/```(?:xml|bpmn)?\s*([\s\S]*?)```/i);
    if (innerBlock) {
      cleaned = innerBlock[1].trim();
    }
  }

  // Si no parece XML, retornar tal cual para que el modelador muestre el error nativo
  if (!cleaned.includes("<") || !cleaned.includes(">")) {
    return { xml: cleaned, autoGeneratedDiagram: false };
  }

  // Verificar si ya tiene sección BPMNDiagram
  const hasDiagram = /<(?:\w+:)?BPMNDiagram\b/i.test(cleaned);
  if (hasDiagram) {
    return { xml: cleaned, autoGeneratedDiagram: false };
  }

  // Si carece de BPMNDiagram, intentar sintetizarlo
  try {
    const enriched = generateDiagramInterchange(cleaned);
    return { xml: enriched, autoGeneratedDiagram: true };
  } catch (error) {
    console.warn("No se pudo autogenerar el BPMNDiagram:", error);
    return { xml: cleaned, autoGeneratedDiagram: false };
  }
}

export interface OrthogonalRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface OrthogonalRouteOptions {
  /** Pasillo horizontal preferido para los retornos (feedback loops). */
  corridorY?: number;
  /** Nodos que la ruta debe esquivar (sin contar origen y destino). */
  obstacles?: OrthogonalRect[];
  /** Margen mínimo entre la ruta y los nodos. */
  padding?: number;
}

type Point = { x: number; y: number };

const EPSILON = 1;

function rectBottom(rect: OrthogonalRect) {
  return rect.y + rect.height;
}

function rectRight(rect: OrthogonalRect) {
  return rect.x + rect.width;
}

/** ¿El segmento vertical `x` entre `y1..y2` atraviesa el rectángulo? */
function verticalHitsRect(x: number, y1: number, y2: number, rect: OrthogonalRect, padding: number) {
  const top = Math.min(y1, y2);
  const bottom = Math.max(y1, y2);
  return (
    x > rect.x - padding &&
    x < rectRight(rect) + padding &&
    bottom > rect.y - padding &&
    top < rectBottom(rect) + padding
  );
}

/** ¿El segmento horizontal `y` entre `x1..x2` atraviesa el rectángulo? */
function horizontalHitsRect(y: number, x1: number, x2: number, rect: OrthogonalRect, padding: number) {
  const left = Math.min(x1, x2);
  const right = Math.max(x1, x2);
  return (
    y > rect.y - padding &&
    y < rectBottom(rect) + padding &&
    right > rect.x - padding &&
    left < rectRight(rect) + padding
  );
}

function isVerticalClear(
  x: number,
  y1: number,
  y2: number,
  obstacles: OrthogonalRect[],
  padding: number,
) {
  return obstacles.every((rect) => !verticalHitsRect(x, y1, y2, rect, padding));
}

function isHorizontalClear(
  y: number,
  x1: number,
  x2: number,
  obstacles: OrthogonalRect[],
  padding: number,
) {
  return obstacles.every((rect) => !horizontalHitsRect(y, x1, x2, rect, padding));
}

/** Busca un pasillo vertical libre cerca del punto medio horizontal. */
function findClearMidX(
  startX: number,
  endX: number,
  y1: number,
  y2: number,
  obstacles: OrthogonalRect[],
  padding: number,
) {
  const low = Math.min(startX, endX);
  const high = Math.max(startX, endX);
  const mid = Math.round((startX + endX) / 2);
  for (let delta = 0; delta <= high - low; delta += 8) {
    for (const candidate of [mid + delta, mid - delta]) {
      if (candidate <= low || candidate >= high) continue;
      if (isVerticalClear(candidate, y1, y2, obstacles, padding)) return candidate;
    }
  }
  return mid;
}

/** Busca un pasillo horizontal libre cerca del punto medio vertical. */
function findClearMidY(
  startY: number,
  endY: number,
  x1: number,
  x2: number,
  obstacles: OrthogonalRect[],
  padding: number,
) {
  const low = Math.min(startY, endY);
  const high = Math.max(startY, endY);
  const mid = Math.round((startY + endY) / 2);
  for (let delta = 0; delta <= high - low; delta += 8) {
    for (const candidate of [mid + delta, mid - delta]) {
      if (candidate <= low || candidate >= high) continue;
      if (isHorizontalClear(candidate, x1, x2, obstacles, padding)) return candidate;
    }
  }
  return mid;
}

/** Quita puntos duplicados y vértices intermedios que no aportan un giro. */
function cleanWaypoints(points: Point[]): Point[] {
  const deduped: Point[] = [];
  for (const point of points) {
    const rounded = { x: Math.round(point.x), y: Math.round(point.y) };
    const previous = deduped[deduped.length - 1];
    if (previous && Math.abs(previous.x - rounded.x) < EPSILON && Math.abs(previous.y - rounded.y) < EPSILON) {
      continue;
    }
    deduped.push(rounded);
  }

  return deduped.filter((point, index) => {
    if (index === 0 || index === deduped.length - 1) return true;
    const previous = deduped[index - 1];
    const next = deduped[index + 1];
    const horizontal = previous.y === point.y && point.y === next.y;
    const vertical = previous.x === point.x && point.x === next.x;
    return !(horizontal || vertical);
  });
}

/**
 * Calcula puntos de enrutamiento ortogonal (ángulos estrictos de 90°) entre dos nodos.
 * - Sale y entra por el lado más cercano según la posición relativa.
 * - Evita diagonales y esquiva los nodos intermedios cuando se le pasan `obstacles`.
 * - Los retornos (target a la izquierda) usan un pasillo inferior limpio, nunca una diagonal
 *   que cruce todo el diagrama.
 */
export function calculateOrthogonalWaypoints(
  source: OrthogonalRect,
  target: OrthogonalRect,
  options: OrthogonalRouteOptions | number = {},
): Point[] {
  const config: OrthogonalRouteOptions =
    typeof options === "number" ? { corridorY: options } : options;
  const padding = config.padding ?? 8;
  const obstacles = (config.obstacles ?? []).filter(
    (rect) =>
      !(
        rect.x === source.x &&
        rect.y === source.y &&
        rect.width === source.width &&
        rect.height === source.height
      ) &&
      !(
        rect.x === target.x &&
        rect.y === target.y &&
        rect.width === target.width &&
        rect.height === target.height
      ),
  );

  const sMidX = Math.round(source.x + source.width / 2);
  const sMidY = Math.round(source.y + source.height / 2);
  const tMidX = Math.round(target.x + target.width / 2);
  const tMidY = Math.round(target.y + target.height / 2);
  const sourceBottom = Math.round(rectBottom(source));
  const targetBottom = Math.round(rectBottom(target));

  // 1) El destino está completamente por encima: salir por arriba y entrar por abajo.
  if (targetBottom <= source.y - 10) {
    const midY = findClearMidY(source.y, targetBottom, sMidX, tMidX, obstacles, padding);
    return cleanWaypoints([
      { x: sMidX, y: source.y },
      { x: sMidX, y: midY },
      { x: tMidX, y: midY },
      { x: tMidX, y: targetBottom },
    ]);
  }

  // 2) El destino está completamente por debajo: salir por abajo y entrar por arriba.
  if (target.y >= sourceBottom + 10) {
    const midY = findClearMidY(sourceBottom, target.y, sMidX, tMidX, obstacles, padding);
    return cleanWaypoints([
      { x: sMidX, y: sourceBottom },
      { x: sMidX, y: midY },
      { x: tMidX, y: midY },
      { x: tMidX, y: target.y },
    ]);
  }

  // 3) Retorno hacia la izquierda: pasillo horizontal limpio por debajo de ambos nodos.
  if (tMidX < sMidX - 6) {
    const desiredCorridor =
      config.corridorY ?? Math.max(sourceBottom, targetBottom) + 45;
    let corridorY = Math.max(desiredCorridor, Math.max(sourceBottom, targetBottom) + padding);
    const low = Math.min(sourceBottom, targetBottom);
    const high = Math.max(corridorY, low + padding);
    for (let candidate = corridorY; candidate <= high + 260; candidate += 8) {
      if (isHorizontalClear(candidate, sMidX, tMidX, obstacles, padding)) {
        corridorY = candidate;
        break;
      }
    }
    return cleanWaypoints([
      { x: sMidX, y: sourceBottom },
      { x: sMidX, y: corridorY },
      { x: tMidX, y: corridorY },
      { x: tMidX, y: targetBottom },
    ]);
  }

  // 4) Flujo horizontal (o casi) hacia la derecha: escalón ortogonal por el centro libre.
  const startX = Math.round(rectRight(source));
  const endX = Math.round(target.x);
  if (Math.abs(sMidY - tMidY) <= 4) {
    return cleanWaypoints([
      { x: startX, y: sMidY },
      { x: endX, y: tMidY },
    ]);
  }

  const midX = findClearMidX(startX, endX, sMidY, tMidY, obstacles, padding);
  return cleanWaypoints([
    { x: startX, y: sMidY },
    { x: midX, y: sMidY },
    { x: midX, y: tMidY },
    { x: endX, y: tMidY },
  ]);
}

interface NodeBounds {
  id: string;
  x: number;
  y: number;
  width: number;
  height: number;
  isEdge?: boolean;
}

/**
 * Sintetiza un bloque <bpmndi:BPMNDiagram> con coordenadas para un XML semántico de BPMN 2.0
 */
export function generateDiagramInterchange(xmlString: string): string {
  const parser = new DOMParser();
  const doc = parser.parseFromString(xmlString, "application/xml");

  const parserError = doc.querySelector("parsererror");
  if (parserError) {
    throw new Error(parserError.textContent || "XML inválido");
  }

  // Localizar el proceso principal
  const processEl =
    doc.querySelector("process") ||
    doc.querySelector("bpmn\\:process") ||
    doc.getElementsByTagNameNS("*", "process")[0];

  if (!processEl) {
    throw new Error("No se encontró el elemento <process> en el XML");
  }

  const processId = processEl.getAttribute("id") || "Process_1";

  // Recopilar elementos visuales
  const elementsToLayout: {
    el: Element;
    id: string;
    tag: string;
    type: "start" | "task" | "gateway" | "end" | "other";
  }[] = [];

  const sequenceFlows: {
    el: Element;
    id: string;
    sourceRef: string;
    targetRef: string;
  }[] = [];

  for (let i = 0; i < processEl.children.length; i++) {
    const child = processEl.children[i];
    const rawTag = child.localName || child.tagName.replace(/^.*:/, "");
    const id = child.getAttribute("id");
    if (!id) continue;

    if (rawTag === "sequenceFlow") {
      sequenceFlows.push({
        el: child,
        id,
        sourceRef: child.getAttribute("sourceRef") || "",
        targetRef: child.getAttribute("targetRef") || "",
      });
      continue;
    }

    let type: "start" | "task" | "gateway" | "end" | "other" = "other";
    if (rawTag.includes("startEvent") || rawTag === "startEvent") type = "start";
    else if (rawTag.includes("endEvent") || rawTag === "endEvent") type = "end";
    else if (rawTag.includes("Gateway") || rawTag.endsWith("gateway")) type = "gateway";
    else if (rawTag.includes("Task") || rawTag.includes("Activity") || rawTag === "task") type = "task";

    elementsToLayout.push({ el: child, id, tag: rawTag, type });
  }

  // Ordenar elementos: starts primero, luego siguiendo sequence flows, luego ends
  const nodeMap = new Map<string, NodeBounds>();
  let currentX = 180;
  const startY = 180;

  // Asignar dimensiones y posiciones secuenciales
  elementsToLayout.forEach((item) => {
    let width = 100;
    let height = 80;
    let offsetY = 0;

    if (item.type === "start" || item.type === "end") {
      width = 36;
      height = 36;
      offsetY = 22; // Alinear verticalmente al centro de las tareas
    } else if (item.type === "gateway") {
      width = 50;
      height = 50;
      offsetY = 15;
    } else if (item.type === "task") {
      const name = item.el.getAttribute("name") || "";
      const len = name.length;
      if (len > 30) {
        width = Math.min(240, Math.max(140, Math.round(len * 2.8)));
        height = Math.min(140, Math.max(80, Math.ceil(len / 20) * 18 + 36));
      } else {
        width = 125;
        height = 80;
      }
    }

    const bounds: NodeBounds = {
      id: item.id,
      x: currentX,
      y: startY + offsetY,
      width,
      height,
    };
    nodeMap.set(item.id, bounds);

    // Separación para el siguiente nodo
    currentX += width + 70;
  });

  // Asegurar namespaces en <definitions>
  const root = doc.documentElement;
  if (!root.getAttribute("xmlns:bpmndi")) {
    root.setAttribute("xmlns:bpmndi", "http://www.omg.org/spec/BPMN/20100524/DI");
  }
  if (!root.getAttribute("xmlns:dc")) {
    root.setAttribute("xmlns:dc", "http://www.omg.org/spec/DD/20100524/DC");
  }
  if (!root.getAttribute("xmlns:di")) {
    root.setAttribute("xmlns:di", "http://www.omg.org/spec/DD/20100524/DI");
  }

  // Construir XML del BPMNDiagram
  const diShapesXml = Array.from(nodeMap.values())
    .map(
      (node) => `      <bpmndi:BPMNShape id="${node.id}_di" bpmnElement="${node.id}">
        <dc:Bounds x="${node.x}" y="${node.y}" width="${node.width}" height="${node.height}" />
      </bpmndi:BPMNShape>`,
    )
    .join("\n");


  const diEdgesXml = sequenceFlows
    .map((flow) => {
      const source = nodeMap.get(flow.sourceRef);
      const target = nodeMap.get(flow.targetRef);

      if (!source || !target) {
        return `      <bpmndi:BPMNEdge id="${flow.id}_di" bpmnElement="${flow.id}">
        <di:waypoint x="200" y="200" />
        <di:waypoint x="300" y="200" />
      </bpmndi:BPMNEdge>`;
      }

      // Enrutamiento ortogonal a 90 grados esquivando el resto de nodos.
      const obstacles = Array.from(nodeMap.values());
      const points = calculateOrthogonalWaypoints(source, target, { obstacles });
      const waypointsXml = points
        .map((pt) => `        <di:waypoint x="${pt.x}" y="${pt.y}" />`)
        .join("\n");

      return `      <bpmndi:BPMNEdge id="${flow.id}_di" bpmnElement="${flow.id}">
${waypointsXml}
      </bpmndi:BPMNEdge>`;
    })
    .join("\n");

  const diagramXml = `
  <bpmndi:BPMNDiagram id="BPMNDiagram_1">
    <bpmndi:BPMNPlane id="BPMNPlane_1" bpmnElement="${processId}">
${diShapesXml}
${diEdgesXml}
    </bpmndi:BPMNPlane>
  </bpmndi:BPMNDiagram>
`;

  // Insertar antes del cierre de </definitions> o </bpmn:definitions>
  const closingTagMatch = xmlString.match(/<\/(?:[a-zA-Z0-9]+:)?definitions>/);
  if (closingTagMatch && closingTagMatch.index !== undefined) {
    const before = xmlString.slice(0, closingTagMatch.index);
    const after = xmlString.slice(closingTagMatch.index);
    return `${before}\n${diagramXml}\n${after}`;
  }

  return xmlString;
}

